use core::arch::{asm, naked_asm};
use kernel::hardware::execution::{Context, UserState};

pub fn set_user_marker(state: &mut UserState, id: usize) {
    state.registers[16] = 0x8800 + id;
}

pub fn set_floating_control(state: &mut UserState, id: usize) {
    state.floating_control = (id as u32 + 2) << 5;
}

pub fn frequency(dtb: usize) -> Option<u64> {
    let pointer = (0xffff_ffc0_0040_0000 + (dtb & 0x1f_ffff)) as *const u32;
    // SAFETY: 固件 DTB 须完整映射到启动固件窗口且解析期间保持不变。
    let tree = unsafe { fdt::Fdt::from_ptr_fallible(pointer) }.unwrap();
    tree.root()
        .unwrap()
        .cpus()
        .unwrap()
        .common_timebase_frequency()
        .unwrap()
}

pub fn set_floating_enabled(enabled: bool) {
    // SAFETY: 当前处理器须允许修改 sstatus，修改期间不得执行浮点指令。
    unsafe {
        if enabled {
            asm!("csrs sstatus, {}", in(reg) 2usize << 13, options(nomem, nostack));
        } else {
            asm!("csrc sstatus, {}", in(reg) 3usize << 13, options(nomem, nostack));
        }
    }
}

pub fn floating_enabled() -> bool {
    let status: usize;
    // SAFETY: 执行环境须允许读取 sstatus。
    unsafe {
        asm!("csrr {}, sstatus", out(reg) status, options(nomem, nostack));
    }
    status & 0x6000 != 0
}

#[unsafe(naked)]
pub extern "C" fn switch(_current: &Context, _next: &Context) -> usize {
    naked_asm!(
        "addi sp, sp, -48",
        "sd ra, 0(sp)",
        "sd s0, 8(sp)",
        "sd s1, 16(sp)",
        "sd s5, 24(sp)",
        "sd s11, 32(sp)",
        "li s0, 41",
        "li s1, 42",
        "li s5, 43",
        "li s11, 44",
        "call {switch}",
        "li a0, 1",
        "li t0, 41",
        "bne s0, t0, 2f",
        "li t0, 42",
        "bne s1, t0, 2f",
        "li t0, 43",
        "bne s5, t0, 2f",
        "li t0, 44",
        "bne s11, t0, 2f",
        "li a0, 0",
        "2:",
        "ld ra, 0(sp)",
        "ld s0, 8(sp)",
        "ld s1, 16(sp)",
        "ld s5, 24(sp)",
        "ld s11, 32(sp)",
        "addi sp, sp, 48",
        "ret",
        switch = sym super::switch_context,
    );
}

